"""Markdown report of a full pipeline run (``results/REPORT.md``)."""

from __future__ import annotations

import json

from .parameters import CALIBRATED_PATH, ModelParams
from .trials import TRIALS

PARAM_DOC = {
    "ec50_sib": ("mg/L", "sibeprenlimab in-vivo EC50 for APRIL neutralisation"),
    "ec50_ata": ("mg/L", "atacicept in-vivo EC50 for APRIL/BAFF neutralisation"),
    "f_ind_gd": ("–", "APRIL/BAFF-independent fraction of Gd-IgA1 production (long-lived PCs)"),
    "f_ind_g": ("–", "APRIL/BAFF-independent fraction of IgG autoantibody production"),
    "t_half_deposit": ("days", "mesangial immune-deposit clearance half-life"),
    "phi": ("–", "reversible (immune-active) share of proteinuria"),
    "w_direct": ("–", "complement-independent share of deposit-driven injury"),
    "c3_share": ("–", "C3a/C3b share of complement injury (rest: C5a/C5b-9)"),
    "loop_gain": ("–", "alternative-pathway amplification loop gain"),
    "f_lectin": ("–", "lectin-pathway share of complement initiation"),
    "k_upcr": ("1/yr per g/g", "proteinuria-driven nephron loss rate"),
    "psi": ("–", "reversible fraction of eGFR suppressed by active injury"),
}


def _pct(v):
    return f"{100 * v:.0f}%"


def render(params: ModelParams, cal_table: list[dict], proj_table: list[dict], twin: dict) -> str:
    fit = json.loads(CALIBRATED_PATH.read_text())["fit"] if CALIBRATED_PATH.exists() else {}
    se = dict(zip(fit.get("names", []), fit.get("se_transformed", [])))
    L = []
    L.append("# IgAN digital twin — run report\n")
    L.append("Generated by `python -m igan_twin all`. All results are model outputs from virtual patients; "
             "they are research hypotheses, not clinical recommendations.\n")

    L.append("## 1. Calibration against published trials\n")
    L.append("Each trial was re-simulated with a fresh virtual cohort (n per arm shown in CLI output). "
             "UPCR targets are placebo-adjusted geometric-mean reductions.\n")
    L.append("| Trial | Endpoint | Arm | Day | Published | Twin |")
    L.append("|---|---|---|---|---|---|")
    for r in cal_table:
        if r["kind"] == "upcr_ratio":
            ep, o, p = "UPCR reduction vs placebo", _pct(1 - r["observed"]), _pct(1 - r["predicted"])
        elif r["kind"] == "egfr_change":
            ep, o, p = "eGFR change (mL/min)", f"{r['observed']:+.1f}", f"{r['predicted']:+.1f}"
        else:
            ep, o, p = "Gd-IgA1 vs baseline", _pct(r["observed"] - 1), _pct(r["predicted"] - 1)
        L.append(f"| {r['trial']} | {ep} | {r['arm']} | {r['day']:g} | {o} | {p} |")
    L.append("\n![calibration](fig_calibration.png)\n\n![trials](fig_trials.png)\n")

    L.append("## 2. Calibrated population parameters\n")
    L.append("| Parameter | Value | Approx. 95% range | Unit | Meaning |")
    L.append("|---|---|---|---|---|")
    import math

    from .parameters import CALIBRATED

    for k, (unit, doc) in PARAM_DOC.items():
        v = getattr(params, k)
        s = se.get(k)
        rng = "–"
        if s is not None and math.isfinite(s):
            tr = CALIBRATED[k][0]
            if tr == "log":
                lo, hi = v * math.exp(-1.96 * s), v * math.exp(1.96 * s)
            else:
                x = math.log(v / (1 - v))
                lo, hi = 1 / (1 + math.exp(-(x - 1.96 * s))), 1 / (1 + math.exp(-(x + 1.96 * s)))
            rng = f"{lo:.3g} – {hi:.3g}"
        L.append(f"| `{k}` | {v:.3g} | {rng} | {unit} | {doc} |")
    L.append("\nRanges are Gauss-Newton approximations including the weak prior; wide ranges flag "
             "parameters the trial summaries cannot pin down.\n")

    L.append("## 3. Mechanism and 10-year strategy projection\n")
    L.append("![mechanism](fig_mechanism.png)\n")
    L.append("| Strategy | UPCR reduction vs SoC (9 mo) | Gd-IgA1 | Deposits | C3 | C5b-9 | eGFR slope yr 1–2 | KF-free at 10 y |")
    L.append("|---|---|---|---|---|---|---|---|")
    for r in proj_table:
        L.append(
            f"| {r['strategy']} | {_pct(r['UPCR reduction vs SoC at 9 mo'])} | {_pct(r['Gd-IgA1 vs baseline'])} | "
            f"{_pct(r['mesangial deposits vs baseline'])} | {_pct(r['C3 deposition vs baseline'])} | "
            f"{_pct(r['C5b-9 vs baseline'])} | {r['eGFR slope yr1-2 (mL/min/yr)']:+.1f} | {_pct(r['kidney failure-free at 10 y'])} |"
        )
    L.append("\nBiomarker columns are geometric-mean levels relative to baseline at 9 months.\n")
    L.append("![long-term](fig_longterm.png)\n\n![precision](fig_precision.png)\n")

    L.append("## 4. Individual twin demonstration\n")
    p = twin["patient"]
    L.append(f"Synthetic patient: eGFR {p['egfr0']}, UPCR {p['upcr0']} g/g, FHR-5/FH ×{p['fhr5_rel']}, "
             f"mesangial C3 {p['c3_int']:g}+, MEST-C M{p['M']}E{p['E']}S{p['S']}T{p['T']}C{p['C']}. "
             "Six monthly visits on sibeprenlimab were simulated from hidden 'true' random effects "
             "with realistic measurement noise; the twin was fitted to those visits only.\n")
    L.append("| Random effect | True | Estimated (± SD) |")
    L.append("|---|---|---|")
    for (k, (m, s)), t in zip(twin["estimated_eta"].items(), twin["true_eta"]):
        L.append(f"| {k} | {t:+.2f} | {m:+.2f} ± {s:.2f} |")
    L.append("\nSix months on an anti-APRIL drug identify the APRIL-dependence and progression effects. They say "
             "almost nothing about the complement share (posterior SD stays near the prior's 1.0), because APRIL "
             "blockade lowers every complement-driven term in proportion. The forecasts for adding or switching "
             "to iptacopan are correspondingly wide. In practice a complement biomarker (urinary C5b-9, plasma "
             "Bb, mesangial C3 on repeat biopsy) or a short iptacopan exposure would narrow them. The twin "
             "reports this uncertainty instead of hiding it.\n")
    L.append("\n| Scenario after month 6 | eGFR at 5 y (twin median) | eGFR at 5 y (truth) | P(kidney failure by 10 y) |")
    L.append("|---|---|---|---|")
    for s, row in twin["forecast_personalised"].items():
        L.append(f"| {s} | {row.get('eGFR_5y_median', float('nan')):.0f} | {twin['truth_eGFR_5y'][s]:.0f} | "
                 f"{_pct(row.get('P_kidney_failure_10y', float('nan')))} |")
    L.append("\n![twin](fig_twin.png)\n")

    L.append("## 5. Sources of calibration data\n")
    for key, t in TRIALS.items():
        for ref in t.refs:
            L.append(f"- **{key}** — {ref}")
    L.append("\n## 6. Limitations\n")
    L.append(
        "- Calibrated to arm-level summary statistics, not individual patient data; inter-individual variability "
        "and covariate effects are priors, not estimates.\n"
        "- ARTEMIS-IGAN placebo response was not published numerically; the null result is used as a weak target.\n"
        "- PK models are effective one-compartment approximations; target-mediated disposition is not modelled.\n"
        "- Long-term eGFR projections rely on the proteinuria–progression link (UPCR as a surrogate); eGFR-slope "
        "results from VISIONARY, ORIGIN 3 and APPLAUSE-IgAN should be used to validate them when available.\n"
        "- The proteinuria-to-nephron-loss rate is calibrated mainly to the steep placebo eGFR losses in ENVISION "
        "and SANCTUARY (about -7 to -9 mL/min/yr). Absolute 10-year kidney-failure rates are therefore "
        "pessimistic for lower-risk patients; relative comparisons between strategies are more robust.\n"
        "- Supportive care (RASi/SGLT2i/endothelin antagonism) is represented as the trial background, not mechanistically.\n"
    )
    return "\n".join(L)
